using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Logging.Abstractions;
using SelfClaw.Core.Interfaces;
using SelfClaw.Core.Models;
using SelfClaw.Infrastructure.Attachments;
using SelfClaw.Infrastructure.ImageGeneration;
using SelfClaw.Infrastructure.Options;

namespace SelfClaw.Desktop.Services.ImageGeneration;

/// <summary>
/// Maps <c>image-generation/*</c> onto the image service. The renderer sends knobs and gets back URLs:
/// generated bytes are written under the generated-images virtual host, so a batch of four 2 MB renders
/// never travels through <c>postMessage</c> as base64 and the renderer never sees a filesystem path.
/// </summary>
internal sealed class ImageGenerationBridge
{
    private const string MessagePrefix = "image-generation/";
    private const int MaxPromptLength = 4000;
    private const int MaxIdentifierLength = 128;
    private const int MaxCount = 10;
    private const int RetentionDays = 7;

    // Base64 spends four characters per three bytes; the ceiling is checked before decoding so an
    // oversized paste is refused before its decoded buffer is allocated. Shares the attachment limit
    // instead of inventing a second one.
    private const int MaximumBase64Length = (AttachmentPathResolver.MaximumByteLength + 2) / 3 * 4;

    private readonly IImageGenerationService _imageService;
    private readonly IAiProviderSettingsService _providerSettingsService;
    private readonly StoragePaths _storagePaths;
    private readonly ILogger<ImageGenerationBridge> _logger;
    private readonly ConcurrentDictionary<string, CancellationTokenSource> _activeJobs = new(StringComparer.Ordinal);

    public ImageGenerationBridge(
        IImageGenerationService imageService,
        IAiProviderSettingsService providerSettingsService,
        StoragePaths storagePaths,
        ILogger<ImageGenerationBridge>? logger = null)
    {
        _imageService = imageService;
        _providerSettingsService = providerSettingsService;
        _storagePaths = storagePaths;
        _logger = logger ?? NullLogger<ImageGenerationBridge>.Instance;
    }

    public async Task<object> TryHandleAsync(
        string type,
        JsonElement payload,
        CancellationToken cancellationToken = default)
    {
        string? requestId = null;
        try
        {
            requestId = ReadOptionalString(payload, "requestId", MaxIdentifierLength);
            return type switch
            {
                "image-generation/list-models" => await HandleListModelsAsync(type, requestId, cancellationToken).ConfigureAwait(false),
                "image-generation/generate" => await HandleGenerateAsync(type, payload, requestId, cancellationToken).ConfigureAwait(false),
                "image-generation/edit" => await HandleEditAsync(type, payload, requestId, cancellationToken).ConfigureAwait(false),
                "image-generation/cancel" => HandleCancel(payload, type, requestId),
                _ => throw new ArgumentException($"Unsupported image generation message '{type}'.")
            };
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
            // Shutdown or window teardown: the request never produced an answer, and inventing a
            // failure result here would hide a real cancellation from the router.
            throw;
        }
        catch (OperationCanceledException)
        {
            // The user cancelled this job. It is a settled outcome, not a failure, so the pending
            // renderer promise resolves instead of waiting for its own timeout.
            return new { type, requestId, ok = false, cancelled = true };
        }
        catch (TimeoutException)
        {
            _logger.LogWarning("Image generation timed out for request '{Type}'", type);
            return new
            {
                type,
                requestId,
                ok = false,
                error = "生图超时：服务端长时间没有返回结果。请减少生成数量、换用更快的模型，或检查网络与代理设置。"
            };
        }
        catch (ArgumentException exception)
        {
            // Bridge-authored validation text, already written for the user.
            _logger.LogWarning("Image generation request '{Type}' was rejected: {Message}", type, exception.Message);
            return new { type, requestId, ok = false, error = exception.Message };
        }
        catch (Exception exception) when (IsConfigurationFault(exception))
        {
            // Enabled/format/credential problems belong to the settings page; logging them as failures
            // would bury real defects in a stream the user can fix themselves.
            _logger.LogWarning("Image generation rejected by configuration: {Message}", exception.Message);
            return new { type, requestId, ok = false, error = $"生图配置有误：{exception.Message}" };
        }
        catch (Exception exception)
        {
            _logger.LogError(exception, "Error handling image generation request '{Type}'", type);
            return new { type, requestId, ok = false, error = $"生图失败：{exception.Message}" };
        }
    }

    private static bool IsConfigurationFault(Exception exception) =>
        exception is InvalidOperationException or NotSupportedException or KeyNotFoundException;

    private async Task<object> HandleListModelsAsync(string type, string? requestId, CancellationToken cancellationToken)
    {
        var state = await _providerSettingsService.GetStateAsync(cancellationToken).ConfigureAwait(false);
        var imageModels = new List<object>();

        foreach (var provider in state.Providers.Where(p => p.Enabled))
        {
            foreach (var model in provider.Models.Where(m => m.Enabled && m.ApiFormat == AiProviderApiFormat.OpenAIImages))
            {
                var capabilities = _imageService.GetModelCapabilities(model.Model);
                imageModels.Add(new
                {
                    profileId = model.ModelProfileId,
                    providerName = provider.Name,
                    name = model.Name,
                    model = model.Model,
                    description = model.Configuration?.Description ?? $"{provider.Name} 图像生成模型",
                    capabilities = new
                    {
                        sizes = capabilities.Sizes,
                        qualities = capabilities.Qualities.Select(ToWireName),
                        styles = capabilities.Styles.Select(ToWireName),
                        maxCount = capabilities.MaxCount
                    }
                });
            }
        }

        return new { type, requestId, ok = true, models = imageModels };
    }

    private Task<object> HandleGenerateAsync(
        string type,
        JsonElement payload,
        string? requestId,
        CancellationToken cancellationToken)
    {
        var request = new ImageGenerationRequest(
            ReadPrompt(payload),
            ReadCount(payload),
            ReadOptionalString(payload, "size", 32),
            ReadOptionalEnum<ImageGenerationQuality>(payload, "quality"),
            ReadOptionalEnum<ImageGenerationStyle>(payload, "style"));

        return RunJobAsync(
            payload,
            type,
            requestId,
            (profileId, token) => _imageService.GenerateImagesAsync(profileId, request, token),
            cancellationToken);
    }

    private async Task<object> HandleEditAsync(
        string type,
        JsonElement payload,
        string? requestId,
        CancellationToken cancellationToken)
    {
        var image = DecodeBase64(ReadRequiredString(payload, "imageBase64", MaximumBase64Length), "参考图");
        var request = new ImageEditRequest(
            image,
            ReadPrompt(payload),
            ReadCount(payload),
            ReadOptionalString(payload, "size", 32));

        return await RunJobAsync(
            payload,
            type,
            requestId,
            (profileId, token) => _imageService.GenerateImageEditsAsync(profileId, request, token),
            cancellationToken).ConfigureAwait(false);
    }

    private object HandleCancel(JsonElement payload, string type, string? requestId)
    {
        var jobId = ReadRequiredString(payload, "jobId", MaxIdentifierLength);
        if (_activeJobs.TryGetValue(jobId, out var source))
        {
            try
            {
                // The owning request disposes the source in its finally block; disposal can win the
                // race against this lookup, in which case the job has already finished.
                source.Cancel();
            }
            catch (ObjectDisposedException)
            {
            }
        }

        return new { type, requestId, ok = true };
    }

    private async Task<object> RunJobAsync(
        JsonElement payload,
        string type,
        string? requestId,
        Func<Guid?, CancellationToken, Task<ImageGenerationResult>> operation,
        CancellationToken cancellationToken)
    {
        var modelProfileId = ReadOptionalGuid(payload, "modelProfileId", "profileId");
        var jobId = ReadOptionalString(payload, "jobId", MaxIdentifierLength);

        using var jobSource = jobId is null ? null : CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
        if (jobId is not null && jobSource is not null)
        {
            _activeJobs[jobId] = jobSource;
        }

        try
        {
            var result = await operation(modelProfileId, jobSource?.Token ?? cancellationToken).ConfigureAwait(false);
            var images = await PersistImagesAsync(result, DateTimeOffset.UtcNow, cancellationToken).ConfigureAwait(false);
            return new
            {
                type,
                requestId,
                ok = true,
                images,
                durationMs = result.Duration.TotalMilliseconds,
                modelProfileId = result.ModelProfileId
            };
        }
        finally
        {
            if (jobId is not null)
            {
                _activeJobs.TryRemove(jobId, out _);
            }
        }
    }

    private async Task<List<object>> PersistImagesAsync(
        ImageGenerationResult result,
        DateTimeOffset now,
        CancellationToken cancellationToken)
    {
        var root = GeneratedImagePathResolver.ResolveRoot(_storagePaths.AppDataDirectory);
        PruneExpiredDays(root, now);

        var images = new List<object>(result.Images.Count);
        foreach (var item in result.Images)
        {
            var id = Guid.NewGuid();
            string? url = null;

            if (item.ImageBytes is { IsEmpty: false } bytes)
            {
                var relativePath = GeneratedImagePathResolver.CreateRelativePath(now, id, DetectExtension(bytes.Span));
                var fullPath = GeneratedImagePathResolver.ResolveFullPath(root, relativePath);
                var directory = Path.GetDirectoryName(fullPath);
                if (!string.IsNullOrEmpty(directory))
                {
                    Directory.CreateDirectory(directory);
                }

                await File.WriteAllBytesAsync(fullPath, bytes, cancellationToken).ConfigureAwait(false);
                url = GeneratedImagePathResolver.CreateSourceUrl(relativePath);
            }
            else if (item.ImageUri is { } imageUri)
            {
                // A gateway that ignores the byte request answers with its own URL; it is not ours to cache.
                url = imageUri.ToString();
            }

            if (url is null)
            {
                continue;
            }

            images.Add(new
            {
                id = id.ToString("N"),
                url,
                revisedPrompt = item.RevisedPrompt
            });
        }

        return images;
    }

    private void PruneExpiredDays(string root, DateTimeOffset now)
    {
        try
        {
            if (!Directory.Exists(root))
            {
                return;
            }

            var cutoff = now.UtcDateTime.Date.AddDays(-RetentionDays);
            foreach (var directory in Directory.EnumerateDirectories(root))
            {
                var name = Path.GetFileName(directory);
                if (!DateTime.TryParseExact(name, "yyyyMMdd", CultureInfo.InvariantCulture, DateTimeStyles.None, out var day)
                    || day >= cutoff)
                {
                    continue;
                }

                Directory.Delete(directory, recursive: true);
            }
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            // Retention is housekeeping: a locked file must never fail the render that triggered it.
            _logger.LogWarning(exception, "Failed to prune generated images under '{Root}'.", root);
        }
    }

    /// <summary>
    /// Gateways answer with whichever format the model produces, so the extension has to come from the
    /// bytes: labelling a JPEG as <c>.png</c> makes the WebView virtual host serve the wrong media type.
    /// </summary>
    private static string DetectExtension(ReadOnlySpan<byte> bytes)
    {
        if (bytes.Length >= 8
            && bytes[0] == 0x89 && bytes[1] == 0x50 && bytes[2] == 0x4E && bytes[3] == 0x47)
        {
            return ".png";
        }

        if (bytes.Length >= 3 && bytes[0] == 0xFF && bytes[1] == 0xD8 && bytes[2] == 0xFF)
        {
            return ".jpg";
        }

        if (bytes.Length >= 12
            && bytes[0] == 0x52 && bytes[1] == 0x49 && bytes[2] == 0x46 && bytes[3] == 0x46
            && bytes[8] == 0x57 && bytes[9] == 0x45 && bytes[10] == 0x42 && bytes[11] == 0x50)
        {
            return ".webp";
        }

        return ".png";
    }

    private static byte[] DecodeBase64(string base64OrDataUri, string label)
    {
        try
        {
            return Convert.FromBase64String(StripDataUriPrefix(base64OrDataUri));
        }
        catch (FormatException exception)
        {
            throw new ArgumentException($"{label}数据无效，请重新选择图片。", nameof(base64OrDataUri), exception);
        }
    }

    private static string StripDataUriPrefix(string base64OrDataUri)
    {
        var commaIndex = base64OrDataUri.IndexOf(',');
        return base64OrDataUri.StartsWith("data:", StringComparison.OrdinalIgnoreCase) && commaIndex >= 0
            ? base64OrDataUri[(commaIndex + 1)..]
            : base64OrDataUri;
    }

    private static string ToWireName<TEnum>(TEnum value) where TEnum : struct, Enum =>
        value.ToString().ToLowerInvariant();

    private static string ReadPrompt(JsonElement payload)
    {
        var prompt = ReadRequiredString(payload, "prompt", MaxPromptLength).Trim();
        return string.IsNullOrEmpty(prompt)
            ? throw new ArgumentException("请输入你想生成的图片描述。")
            : prompt;
    }

    private static int ReadCount(JsonElement payload)
    {
        var count = ReadOptionalInt(payload, "count") ?? 1;
        return count is >= 1 and <= MaxCount
            ? count
            : throw new ArgumentException($"生成数量需在 1 到 {MaxCount} 之间。");
    }

    private static TEnum? ReadOptionalEnum<TEnum>(JsonElement payload, string name) where TEnum : struct, Enum
    {
        var raw = ReadOptionalString(payload, name, 32);
        if (string.IsNullOrWhiteSpace(raw))
        {
            return null;
        }

        return Enum.TryParse<TEnum>(raw, ignoreCase: true, out var parsed) && Enum.IsDefined(parsed)
            ? parsed
            : throw new ArgumentException($"不支持的 {name} 取值 '{raw}'。");
    }

    private static string ReadRequiredString(JsonElement payload, string name, int maximumLength)
    {
        var value = ReadOptionalString(payload, name, maximumLength)
            ?? throw new ArgumentException($"缺少必填参数 {name}。");
        return value;
    }

    private static string? ReadOptionalString(JsonElement payload, string name, int maximumLength)
    {
        if (!payload.TryGetProperty(name, out var prop) || prop.ValueKind != JsonValueKind.String)
        {
            return null;
        }

        var value = prop.GetString();
        return value is not null && value.Length > maximumLength
            ? throw new ArgumentException($"参数 {name} 过长（上限 {maximumLength} 字符）。")
            : value;
    }

    private static Guid? ReadOptionalGuid(JsonElement payload, params string[] names)
    {
        foreach (var name in names)
        {
            if (payload.TryGetProperty(name, out var prop)
                && prop.ValueKind == JsonValueKind.String
                && Guid.TryParse(prop.GetString(), out var guid))
            {
                return guid;
            }
        }

        return null;
    }

    private static int? ReadOptionalInt(JsonElement payload, string name)
        => payload.TryGetProperty(name, out var prop) && prop.TryGetInt32(out var value) ? value : null;
}
